#!/usr/bin/env node
// GameVerse design tokens generator. Node built-ins only, no dependencies.
//
//   node packages/design-tokens/build.mjs           regenerate every output from tokens.json
//   node packages/design-tokens/build.mjs --check   fail if an output is missing, stale, or lacks a token
//
// Outputs (all committed, so web and Unity builds don't need Node):
//   apps/web/src/styles/tokens.css, apps/admin/src/styles/tokens.css   CSS custom properties, every token
//   apps/mobile/Assets/GameVerse/UI/Tokens.uss                          USS variables, every token USS can express
//   apps/mobile/Assets/GameVerse/UI/Tokens.g.cs                         C# constants, every token (code tweens, fonts)
//   apps/web/src/styles/theme.css, apps/admin/src/styles/theme.css     Tailwind v4 @theme mapping utilities onto --gv-*

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = resolve(HERE, '..', '..');
export const TOKENS_FILE = join(HERE, 'tokens.json');

export const OUTPUTS = [
  { path: 'apps/web/src/styles/tokens.css', kind: 'css' },
  { path: 'apps/admin/src/styles/tokens.css', kind: 'css' },
  { path: 'apps/mobile/Assets/GameVerse/UI/Tokens.uss', kind: 'uss' },
  { path: 'apps/mobile/Assets/GameVerse/UI/Tokens.g.cs', kind: 'cs' },
  { path: 'apps/web/src/styles/theme.css', kind: 'tailwind' },
  { path: 'apps/admin/src/styles/theme.css', kind: 'tailwind' },
];

const GENERATED = 'GENERATED by packages/design-tokens/build.mjs from tokens.json. Do not edit; run `make tokens`.';
const CSS_PREFIX = '--gv-';
const KEY = /^[a-z0-9]+(-[a-z0-9]+)*$/;

// CSS easing keywords as cubic-bezier control points (CSS Easing Functions Level 1), for the C# output.
const EASING_KEYWORDS = {
  linear: [0, 0, 1, 1],
  ease: [0.25, 0.1, 0.25, 1],
  'ease-in': [0.42, 0, 1, 1],
  'ease-out': [0, 0, 0.58, 1],
  'ease-in-out': [0.42, 0, 0.58, 1],
};

// ---------------------------------------------------------------------------------------------
// Parsing and validation
// ---------------------------------------------------------------------------------------------

const VALIDATORS = {
  color: (v) => typeof v === 'string' && /^#[0-9A-Fa-f]{6}([0-9A-Fa-f]{2})?$/.test(v) || 'expected #RRGGBB or #RRGGBBAA',
  dimension: (v) => typeof v === 'string' && /^-?\d+(\.\d+)?(px|em)$/.test(v) || 'expected a number with px or em, e.g. "16px"',
  number: (v) => typeof v === 'number' && Number.isFinite(v) || 'expected a finite number',
  duration: (v) => typeof v === 'string' && /^\d+ms$/.test(v) || 'expected whole milliseconds, e.g. "160ms"',
  cubicBezier: (v) =>
    (typeof v === 'string' && v in EASING_KEYWORDS) ||
    (Array.isArray(v) && v.length === 4 && v.every((n) => typeof n === 'number' && Number.isFinite(n)) &&
      v[0] >= 0 && v[0] <= 1 && v[2] >= 0 && v[2] <= 1) ||
    'expected [x1, y1, x2, y2] with x in 0..1, or one of ' + Object.keys(EASING_KEYWORDS).join(', '),
  fontFamily: (v) =>
    Array.isArray(v) && v.length > 0 && v.every((f) => typeof f === 'string' && /^[A-Za-z0-9 ]+$/.test(f)) ||
    'expected a non-empty array of family names (letters, digits, spaces)',
  fontWeight: (v) => Number.isInteger(v) && v >= 100 && v <= 900 && v % 100 === 0 || 'expected 100, 200, ... 900',
  string: (v) => typeof v === 'string' && /^[a-z0-9-]+$/.test(v) || 'expected a lowercase CSS keyword',
};

/** Flattens tokens.json into [{ path: string[], type, value, description }], validating as it goes. */
export function parseTokens(tree) {
  const tokens = [];
  const errors = [];

  const walk = (node, path) => {
    if (node === null || typeof node !== 'object' || Array.isArray(node)) {
      errors.push(`${path.join('.') || '(root)'}: expected an object`);
      return;
    }
    if ('$value' in node) {
      const where = path.join('.');
      if (path.length === 0) errors.push('(root): a token needs a name');
      const validate = VALIDATORS[node.$type];
      if (!validate) {
        errors.push(`${where}: unknown $type ${JSON.stringify(node.$type)} (known: ${Object.keys(VALIDATORS).join(', ')})`);
        return;
      }
      const ok = validate(node.$value);
      if (ok !== true) {
        errors.push(`${where}: invalid ${node.$type} ${JSON.stringify(node.$value)}: ${ok}`);
        return;
      }
      for (const k of Object.keys(node)) {
        if (!['$type', '$value', '$description'].includes(k)) errors.push(`${where}: unexpected key "${k}"`);
      }
      tokens.push({ path, type: node.$type, value: node.$value, description: node.$description ?? '' });
      return;
    }
    for (const [key, child] of Object.entries(node)) {
      if (key === '$description') continue;
      if (key.startsWith('$')) {
        errors.push(`${[...path, key].join('.')}: "${key}" is only valid on a token`);
        continue;
      }
      if (!KEY.test(key)) {
        errors.push(`${[...path, key].join('.')}: key "${key}" must be lowercase kebab-case`);
        continue;
      }
      walk(child, [...path, key]);
    }
  };

  walk(tree, []);

  const seen = new Map();
  for (const t of tokens) {
    const name = cssName(t);
    if (seen.has(name)) errors.push(`${tokenId(t)} and ${tokenId(seen.get(name))} both become ${name}`);
    else seen.set(name, t);
  }
  const seenTailwind = new Map();
  for (const t of tokens) {
    const name = tailwindName(t);
    if (name === null) continue;
    if (seenTailwind.has(name)) errors.push(`${tokenId(t)} and ${tokenId(seenTailwind.get(name))} both become Tailwind ${name}`);
    else seenTailwind.set(name, t);
  }
  errors.push(...csharpNameErrors(tokens));

  if (errors.length) throw new TokenError(errors);
  return tokens;
}

export class TokenError extends Error {
  constructor(errors) {
    super('Invalid tokens.json:\n  ' + errors.join('\n  '));
    this.errors = errors;
  }
}

export const tokenId = (t) => t.path.join('.');
export const cssName = (t) => CSS_PREFIX + t.path.join('-');

// ---------------------------------------------------------------------------------------------
// CSS and USS
// ---------------------------------------------------------------------------------------------

function cssValue(t) {
  switch (t.type) {
    case 'cubicBezier':
      return Array.isArray(t.value) ? `cubic-bezier(${t.value.join(', ')})` : t.value;
    case 'fontFamily':
      return [...t.value.map((f) => `"${f}"`), 'sans-serif'].join(', ');
    default:
      return String(t.value);
  }
}

/**
 * Whether Unity USS can hold this token as a variable. USS has no line-height or numeric font weight,
 * loads fonts as assets rather than family names, takes only px lengths and only keyword easings.
 * Everything rejected here is still available to Unity through Tokens.g.cs.
 */
export function ussSupports(t) {
  switch (t.type) {
    case 'color':
    case 'duration':
      return true;
    case 'dimension':
      return t.value.endsWith('px');
    case 'number':
      return !t.path.includes('line-height');
    case 'cubicBezier':
      return typeof t.value === 'string';
    default:
      return false;
  }
}

function renderVariables(tokens, comment) {
  const lines = [];
  let group = null;
  for (const t of tokens) {
    if (group !== null && t.path[0] !== group) lines.push('');
    group = t.path[0];
    lines.push(`  ${cssName(t)}: ${cssValue(t)};`);
  }
  return `/* ${comment} */\n:root {\n${lines.join('\n')}\n}\n`;
}

export function renderCss(tokens) {
  return renderVariables(tokens, GENERATED);
}

export function renderUss(tokens) {
  const supported = tokens.filter(ussSupports);
  const skipped = tokens.filter((t) => !ussSupports(t));
  let out = renderVariables(supported, GENERATED + ' Unity UI Toolkit stylesheet: add it to the root PanelSettings theme.');
  if (skipped.length) {
    out += '\n/* Not expressible in USS, use GameVerseTokens in Tokens.g.cs:\n' +
      skipped.map((t) => `   ${tokenId(t)}`).join('\n') + '\n*/\n';
  }
  return out;
}

// ---------------------------------------------------------------------------------------------
// Tailwind v4 theme. Maps utility namespaces onto the --gv-* variables from tokens.css, and resets
// Tailwind's defaults in those namespaces so only token values exist (no bg-red-500, no p-5, no rounded-2xl).
// ---------------------------------------------------------------------------------------------

/** Tailwind theme variable for a token, or null when Tailwind has no namespace for it. */
export function tailwindName(t) {
  const [group, sub] = t.path;
  const last = t.path[t.path.length - 1];
  if (group === 'color') return '--color-' + t.path.slice(1).join('-');
  if (group === 'font' && sub === 'family') return '--font-' + last;
  if (group === 'font' && sub === 'size') return '--text-' + last;
  if (group === 'font' && sub === 'line-height') return '--leading-' + last;
  if (group === 'font' && sub === 'letter-spacing') return '--tracking-' + last;
  if (group === 'font' && sub === 'weight') return '--font-weight-' + last;
  if (group === 'space') return '--spacing-' + last;
  if (group === 'layout') return '--spacing-' + t.path.slice(1).join('-');
  if (group === 'radius') return '--radius-' + last;
  if (group === 'motion' && last === 'easing') return '--ease-' + sub;
  return null;
}

const TAILWIND_RESETS = [
  '--color-*', '--font-*', '--text-*', '--leading-*', '--tracking-*',
  '--spacing', '--spacing-*', '--radius-*', '--ease-*', '--animate-*', '--shadow-*', '--inset-shadow-*', '--drop-shadow-*',
];

export function renderTailwind(tokens) {
  const mapped = tokens.filter((t) => tailwindName(t) !== null);
  const unmapped = tokens.filter((t) => tailwindName(t) === null);
  const lines = TAILWIND_RESETS.map((r) => `  ${r}: initial;`);
  // Without the spacing multiplier, *-0 utilities (inset-0, top-0, p-0) would compute to nothing. Zero is not a design value.
  lines.push('  --spacing-0: 0px;');
  let group = null;
  for (const t of mapped) {
    if (t.path[0] !== group) lines.push('');
    group = t.path[0];
    lines.push(`  ${tailwindName(t)}: var(${cssName(t)});`);
  }
  let out = `/* ${GENERATED} Import after tokens.css and tailwindcss. */\n@theme inline {\n${lines.join('\n')}\n}\n`;
  if (unmapped.length) {
    out += '\n/* No Tailwind namespace, use the variable directly, e.g. duration-(--gv-motion-fast-duration):\n' +
      unmapped.map((t) => `   ${tokenId(t)}  ${cssName(t)}`).join('\n') + '\n*/\n';
  }
  return out;
}

// ---------------------------------------------------------------------------------------------
// C# (Unity). C# 9, no records, matches the Unity 6 compiler like shared/.
// ---------------------------------------------------------------------------------------------

/** kebab segment -> PascalCase identifier. Segments starting with a digit get a leading underscore (space.16 -> _16). */
export function csharpIdent(segment) {
  const pascal = segment.split('-').map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
  return /^[0-9]/.test(pascal) ? '_' + pascal : pascal;
}

function csharpNameErrors(tokens) {
  const errors = [];
  const members = new Map(); // "Color.Bg" -> Map(ident -> tokenId)
  for (const t of tokens) {
    const idents = t.path.map(csharpIdent);
    for (let depth = 0; depth < idents.length; depth++) {
      const scope = ['GameVerseTokens', ...idents.slice(0, depth)].join('.');
      const ident = idents[depth];
      const owner = depth === 0 ? 'GameVerseTokens' : idents[depth - 1];
      if (ident === owner) errors.push(`${tokenId(t)}: C# member ${ident} has the same name as its enclosing class`);
      const isLeaf = depth === idents.length - 1;
      const key = scope + '|' + ident;
      const kind = isLeaf ? 'field' : 'class';
      const prev = members.get(key);
      if (prev && (prev.kind !== kind || isLeaf)) {
        errors.push(`${tokenId(t)}: C# name ${scope}.${ident} collides with ${prev.id}`);
      } else if (!prev) {
        members.set(key, { kind, id: tokenId(t) });
      }
    }
  }
  return errors;
}

const csFloat = (n) => {
  const s = String(Number(n.toPrecision(12)));
  return (s.includes('.') || s.includes('e') ? s : s + '.0') + 'f';
};
const csString = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
const xmlEscape = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function csharpMember(t) {
  const name = csharpIdent(t.path[t.path.length - 1]);
  switch (t.type) {
    case 'color': {
      const hex = t.value.slice(1);
      const ch = (i) => parseInt(hex.slice(i, i + 2), 16);
      const a = hex.length === 8 ? ch(6) : 255;
      return { doc: t.value, code: `public static readonly Color32 ${name} = new Color32(${ch(0)}, ${ch(2)}, ${ch(4)}, ${a});` };
    }
    case 'dimension': {
      return { doc: t.value, code: `public const float ${name} = ${csFloat(parseFloat(t.value))};` };
    }
    case 'number':
      return { doc: String(t.value), code: `public const float ${name} = ${csFloat(t.value)};` };
    case 'duration': {
      const ms = parseInt(t.value, 10);
      return { doc: `${t.value}, in seconds for DOTween/LitMotion`, code: `public const float ${name} = ${csFloat(ms / 1000)};` };
    }
    case 'cubicBezier': {
      const p = Array.isArray(t.value) ? t.value : EASING_KEYWORDS[t.value];
      const doc = Array.isArray(t.value) ? `cubic-bezier(${p.join(', ')})` : `${t.value} = cubic-bezier(${p.join(', ')})`;
      return { doc, code: `public static readonly CubicBezier ${name} = new CubicBezier(${p.map(csFloat).join(', ')});` };
    }
    case 'fontFamily':
      return {
        doc: t.value.join(', '),
        code: `public static readonly IReadOnlyList<string> ${name} = Array.AsReadOnly(new[] { ${t.value.map(csString).join(', ')} });`,
      };
    case 'fontWeight':
      return { doc: String(t.value), code: `public const int ${name} = ${t.value};` };
    case 'string':
      return { doc: t.value, code: `public const string ${name} = ${csString(t.value)};` };
    default:
      throw new Error(`no C# mapping for ${t.type}`);
  }
}

export function renderCs(tokens) {
  // Build a tree of classes in token order.
  const root = { children: new Map(), fields: [] };
  for (const t of tokens) {
    let node = root;
    for (const seg of t.path.slice(0, -1)) {
      if (!node.children.has(seg)) node.children.set(seg, { children: new Map(), fields: [] });
      node = node.children.get(seg);
    }
    node.fields.push(t);
  }

  const out = [];
  const emit = (depth, line) => out.push(line === '' ? '' : '    '.repeat(depth) + line);

  const emitNode = (node, depth) => {
    let first = true;
    const gap = () => { if (!first) emit(0, ''); first = false; };
    for (const t of node.fields) {
      const m = csharpMember(t);
      gap();
      const summary = t.description ? `${xmlEscape(t.description)} (${xmlEscape(m.doc)})` : xmlEscape(m.doc);
      emit(depth, `/// <summary>${summary}</summary>`);
      emit(depth, `${m.code} // token: ${tokenId(t)}`);
    }
    for (const [seg, child] of node.children) {
      gap();
      emit(depth, `public static class ${csharpIdent(seg)}`);
      emit(depth, '{');
      emitNode(child, depth + 1);
      emit(depth, '}');
    }
  };

  emit(0, '// <auto-generated>');
  emit(0, `// ${GENERATED}`);
  emit(0, '// </auto-generated>');
  emit(0, 'using System;');
  emit(0, 'using System.Collections.Generic;');
  emit(0, 'using UnityEngine;');
  emit(0, '');
  emit(0, 'namespace GameVerse.UI');
  emit(0, '{');
  emit(1, '/// <summary>Design tokens for code: tweens, runtime styling, font selection. Stylesheets use Tokens.uss.</summary>');
  emit(1, 'public static class GameVerseTokens');
  emit(1, '{');
  emit(2, '/// <summary>Cubic bezier easing control points, as in CSS cubic-bezier(x1, y1, x2, y2).</summary>');
  emit(2, 'public readonly struct CubicBezier');
  emit(2, '{');
  emit(3, 'public CubicBezier(float x1, float y1, float x2, float y2)');
  emit(3, '{');
  emit(4, 'X1 = x1;');
  emit(4, 'Y1 = y1;');
  emit(4, 'X2 = x2;');
  emit(4, 'Y2 = y2;');
  emit(3, '}');
  emit(0, '');
  emit(3, 'public float X1 { get; }');
  emit(3, 'public float Y1 { get; }');
  emit(3, 'public float X2 { get; }');
  emit(3, 'public float Y2 { get; }');
  emit(2, '}');
  emit(0, '');
  emitNode(root, 2);
  emit(1, '}');
  emit(0, '}');
  return out.join('\n') + '\n';
}

// ---------------------------------------------------------------------------------------------
// Outputs and the completeness check
// ---------------------------------------------------------------------------------------------

const RENDERERS = { css: renderCss, uss: renderUss, cs: renderCs, tailwind: renderTailwind };

export function render(tokens) {
  return OUTPUTS.map((o) => ({ ...o, content: RENDERERS[o.kind](tokens) }));
}

/** Tokens that should appear in an output of this kind but are not declared in its content. */
export function missingTokens(tokens, kind, content) {
  if (kind === 'cs') {
    const found = new Set([...content.matchAll(/\/\/ token: ([a-z0-9.-]+)$/gm)].map((m) => m[1]));
    return tokens.filter((t) => !found.has(tokenId(t))).map(tokenId);
  }
  if (kind === 'tailwind') {
    const found = new Set([...content.matchAll(/^\s*(--[a-z0-9-]+)\s*:\s*var\((--gv-[a-z0-9-]+)\)/gm)].map((m) => m[1] + '=' + m[2]));
    return tokens.filter((t) => tailwindName(t) !== null && !found.has(tailwindName(t) + '=' + cssName(t))).map(tokenId);
  }
  const found = new Set([...content.matchAll(/^\s*(--gv-[a-z0-9-]+)\s*:/gm)].map((m) => m[1]));
  const expected = kind === 'uss' ? tokens.filter(ussSupports) : tokens;
  return expected.filter((t) => !found.has(cssName(t))).map(tokenId);
}

/** Compares files on disk (path -> content or undefined) against what tokens.json generates. Returns problems. */
export function checkOutputs(tokens, readFile) {
  const problems = [];
  for (const o of render(tokens)) {
    const actual = readFile(o.path);
    if (actual === undefined) {
      problems.push(`${o.path}: missing`);
      continue;
    }
    const normalized = actual.replace(/\r\n/g, '\n');
    const missing = missingTokens(tokens, o.kind, normalized);
    for (const id of missing) problems.push(`${o.path}: token ${id} is missing`);
    if (normalized !== o.content) problems.push(`${o.path}: out of date with tokens.json`);
  }
  return problems;
}

function main(argv) {
  const tokens = parseTokens(JSON.parse(readFileSync(TOKENS_FILE, 'utf8')));

  if (argv.includes('--check')) {
    const problems = checkOutputs(tokens, (p) => {
      const full = join(REPO_ROOT, p);
      return existsSync(full) ? readFileSync(full, 'utf8') : undefined;
    });
    if (problems.length) {
      console.error('Design tokens check failed:\n  ' + problems.join('\n  ') + '\nRun `make tokens` to regenerate.');
      return 1;
    }
    console.log(`Design tokens OK: ${tokens.length} tokens, ${OUTPUTS.length} outputs up to date.`);
    return 0;
  }

  for (const o of render(tokens)) {
    const full = join(REPO_ROOT, o.path);
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, o.content);
    console.log(`wrote ${o.path}`);
  }
  console.log(`${tokens.length} tokens.`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (e) {
    console.error(e instanceof TokenError ? e.message : e);
    process.exitCode = 1;
  }
}
